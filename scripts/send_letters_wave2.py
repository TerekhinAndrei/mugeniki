def body(m):
    qs = list(m["q"]) + COMMON_Q
    numbered = "\n".join(f"{i}. {q}" for i, q in enumerate(qs, start=1))
    return (f"{m['head']}\n\n{INTRO}\n\n{m['hook']}\n\n{m['why']}\n\n"
            f"つきましては、以下をご教示いただけますでしょうか。\n\n{numbered}\n\n{CLOSE}\n\n{SIGN}\n")


def main():
    out = []
    for m in MAKERS:
        text = body(m)
        path = pathlib.Path(f"mugeniki/letters/wave2-{m['key']}.txt")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        p = subprocess.run(
            ["python3", str(GW), "gmail", "send", "--to", m["to"], "--subject", m["subject"], "--body", text],
            capture_output=True, text=True, cwd=str(GW.parents[2]))
        try:
            res = json.loads(p.stdout)
        except Exception:
            res = {"raw": p.stdout, "err": p.stderr}
        out.append(dict(key=m["key"], to=m["to"], subject=m["subject"], result=res))
        print(m["key"], m["to"], res.get("status") or res.get("err") or p.stderr[:120])
    pathlib.Path("mugeniki/letters/wave2-sent.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
